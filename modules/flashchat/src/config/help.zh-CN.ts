export const guideZh = (historyLimit: string, messageLimit: string) => `
### 使用指南

闪聊完整复用 Chitchatter，让每个人都能进行安全、私密的通信。完整项目说明见 [Chitchatter README](https://github.com/jeremyckahn/chitchatter/blob/develop/README.md)。

#### 聊天房间

**任何知道房间链接的人**都能加入公开房间。默认名称在本机随机生成，难以猜测。你可以自定义名称，但简单名称更容易被别人猜到。需要更高安全性时，建议保留默认随机名称。

私密房间只连接输入相同密码的成员。请提前通过可信方式约定密码。密码不同的成员看起来进入了同一房间，但无法彼此连接。由于没有中央服务核对密码，**密码不匹配不会显示错误**。

可通过 [Burner Note](https://burnernote.com/) 或 [Yopass](https://yopass.se/) 等安全工具分享房间链接。有人加入时，页面会显示提示。

##### 核验成员身份

连接建立后，Chitchatter 会自动尝试通过[公钥密码学](https://en.wikipedia.org/wiki/Public-key_cryptography)核验对方。成员列表显示每个人的公钥。公钥不是秘密，可以分享给对方，方便对方准确识别你的身份。

公钥和私钥都在本机生成。私钥不会发送给其他成员或服务器。

##### 补齐聊天记录

聊天记录仅保存在运行中的内存，不写入磁盘。离开房间或关闭窗口后，本机记录会清除。在 WinOne 主窗口切换其他功能后再返回，闪聊会话仍保留。

新成员加入已有成员的**公开房间**时，会自动向其他成员请求此前的聊天记录。所有人离开后，记录彻底消失。加入**私密房间**时不会补齐此前记录。

每个房间最多保留 ${historyLimit} 条消息。

#### 编写消息

消息支持 [GitHub 风格 Markdown](https://github.github.com/gfm/)，并支持代码语法高亮。

按 Enter 发送消息，按 Shift + Enter 换行。单条消息最多 ${messageLimit} 个字符。
`

