import {readNativeState} from "./native-state.mjs";
import {clickPrivateCanvas} from "./native-probe-input.mjs";
import {createRequire} from "node:module";
import {readFile,writeFile} from "node:fs/promises";
import {resolve} from "node:path";
const require=createRequire(import.meta.url),{chromium}=require(process.env.WINONE_PLAYWRIGHT_MODULE||"playwright");
const output=process.env.WINONE_NATIVE_PROBE_OUTPUT;if(!output)throw Error("Set WINONE_NATIVE_PROBE_OUTPUT");
const browser=await chromium.connectOverCDP(process.env.WINONE_NATIVE_PROBE_CDP||"http://127.0.0.1:43192");
try{
 const page=browser.contexts()[0].pages()[0];
 const root=page.locator("[data-native-window]");await root.waitFor();
 const original=await root.getAttribute("data-native-window");
 await page.getByRole("button",{name:"文字",exact:true}).click();await clickPrivateCanvas(output,124,124);
 const cancelled=page.getByRole("textbox",{name:"输入文字",exact:true});await cancelled.fill("取消这段文字");await cancelled.press("Escape");
 await cancelled.waitFor({state:"detached"});
 if(await root.getAttribute("data-annotations")!=="1")throw Error("Cancelled text became an annotation");
 await page.getByRole("button",{name:"文字",exact:true}).click();await clickPrivateCanvas(output,124,124);
 const input=page.getByRole("textbox",{name:"输入文字",exact:true});await input.waitFor();
 await input.fill("你好，WinOne\n直接编辑");
 const textBox=await input.boundingBox(),button=await page.getByRole("button",{name:"文字",exact:true}).boundingBox();
 if(!textBox||!button||textBox.y>=button.y)throw Error("Text entry appeared inside the toolbar");
 await input.evaluate(node=>node.style.caretColor="transparent");
 await input.screenshot({path:resolve(output,"typing.png")});
 const editing=(await readNativeState(resolve(output,"state.json")));
 if(editing.nativeForms!==1||!editing.inputRegion?.textInside||!editing.inputRegion?.toolbarInside||!editing.inputRegion?.gapOutside)throw Error("Text window or native input region is incorrect");
 await page.getByRole("button",{name:"保存",exact:true}).click();
 await input.waitFor({state:"detached"});
 await page.waitForFunction(()=>document.querySelector("[data-annotations]").dataset.annotations==="2");
 await page.waitForFunction(()=>!document.querySelector("button").disabled);
 await page.getByRole("button",{name:"撤销",exact:true}).click();
 await page.waitForFunction(()=>document.querySelector("[data-annotations]").dataset.annotations==="1");
 await page.getByRole("button",{name:"重做",exact:true}).click();
 await page.waitForFunction(()=>document.querySelector("[data-annotations]").dataset.annotations==="2");
 await page.getByRole("button",{name:"保存",exact:true}).click();await page.waitForFunction(()=>!document.querySelector("button").disabled);
 const state=(await readNativeState(resolve(output,"state.json")));
 if(state.nativeWindow!==original||state.toolbarRoot!==original||state.saved!==2)throw Error("Inline text changed the window or failed to save");
 await writeFile(resolve(output,"text-verification.json"),JSON.stringify({textBox,toolbarButton:button,editing,state},null,2));
 const closed=page.waitForEvent("close",{timeout:10000});await page.getByRole("button",{name:"取消",exact:true}).click();await closed;
 console.log("PASS: on-image multiline Chinese input, commit, native undo/redo, save and close in the same window");
}finally{await browser.close();}
