// Reuse the complete upstream helper, not an independently maintained copy.
import {readFileSync,writeFileSync} from 'node:fs';
import {resolve,join} from 'node:path';
import {createRequire} from 'node:module';
import {createHash} from 'node:crypto';
import {execFileSync} from 'node:child_process';
const root=resolve(import.meta.dirname,'..'),source=resolve(process.argv[2]??'');
if(!process.argv[2])throw Error('Usage: node build/prepare-ai-model-tells.mjs <magpie-source>');
const require=createRequire(join(root,'apps/desktop/frontend/package.json')),{parse}=require('@babel/parser');
const original=readFileSync(join(source,'internal/gui/assets/app.js'),'utf8');
const helper=parse(original,{sourceType:'script'}).program.body.find(n=>n.type==='FunctionDeclaration'&&n.id.name==='modelTells');
if(!helper)throw Error('Upstream modelTells helper changed');
const text='// Magpie modelTells, MIT. Generated by build/prepare-ai-model-tells.mjs.\n// Original attribution: third_party/licenses/upstream-magpie-'+execFileSync('git',['-C',source,'rev-parse','HEAD'],{encoding:'utf8',windowsHide:true}).trim()+'-0-LICENSE.txt\nexport '+original.slice(helper.start,helper.end)+'\n';
writeFileSync(join(root,'apps/desktop/frontend/src/features/magpie-model-tells.js'),text);
console.log('Prepared complete upstream modelTells: '+createHash('sha256').update(text).digest('hex'));
