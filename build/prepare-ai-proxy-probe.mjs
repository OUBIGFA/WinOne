// Reuse the pinned GUI's pure proxy check without linking its desktop service.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { execFileSync } from 'node:child_process';

const root = path.resolve(import.meta.dirname, '..');
const [source, output, ...flags] = process.argv.slice(2);
if (!source || !output) throw new Error('Pass the pinned Magpie source and owned entry directory');
const revision = execFileSync('git', ['-C', source, 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim();
const names = ['internal/gui/proxycheck.go', 'internal/gui/proxies.go'];
const inputs = Object.fromEntries(names.map(name => [name, fs.readFileSync(path.join(source, name))]));
const text = Object.fromEntries(names.map(name => [name, inputs[name].toString('utf8').replaceAll('\r\n', '\n')]));
const checksum = bytes => crypto.createHash('sha256').update(bytes).digest('hex');
function declaration(body, prefix) {
  const start = body.indexOf(prefix), end = body.indexOf('\n}', start);
  if (start < 0 || end < start) throw new Error(`Pinned proxy declaration changed: ${prefix}`);
  return body.slice(start, end + 2);
}
const check = text[names[0]], proxies = text[names[1]];
const handler = check.indexOf('func handleProxyCheck(');
if (handler < 0 || !check.includes('\t"sync"')) throw new Error('Pinned proxy check boundary changed');
const support = check.slice(0, handler).replace(/^package gui$/m, 'package main').replace('\t"sync"', '\t"sync"\n\t"sync/atomic"');
const generated = `// Code generated by build/prepare-ai-proxy-probe.mjs from Magpie ${revision}; DO NOT EDIT.
// MIT license: third_party/licenses/upstream-magpie-${revision}-0-LICENSE.txt
${support}
${declaration(proxies, 'type proxyTestJSON struct {')}
var proxyTestClient = http.DefaultClient
${declaration(proxies, 'func testProxy(')}
`;
const manifestPath = path.join(root, 'third_party/magpie-native-proxy-probe.json');
const files = ['build/prepare-ai-proxy-probe.mjs', 'modules/ai-magpie/proxy_probe.go'];
const manifest = {
  schemaVersion: 1,
  repository: 'https://github.com/yetone/magpie',
  revision,
  license: 'MIT',
  notice: `licenses/upstream-magpie-${revision}-0-LICENSE.txt`,
  sourceFiles: Object.fromEntries(names.map(name => [name, checksum(inputs[name])])),
  files: Object.fromEntries(files.map(name => [name, checksum(fs.readFileSync(path.join(root, name)))])),
  generatedFile: 'cmd/winone-ai/upstream_proxy_probe.go',
  generatedSHA256: checksum(Buffer.from(generated)),
  adaptations: [
    'Rename only the package; copy the original pure trace, connection check, latency calculation and error redaction',
    'Omit the GUI HTTP controller and saved-proxy management; the existing WinOne inline proxy supplies the current choice',
    'The Host returns only check state, exit IP/region and redacted failure details'
  ]
};
if (flags.includes('--update')) fs.writeFileSync(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`, 'utf8');
const kept = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));
// Intake has already checked the selected HEAD. Identical source bytes can be
// reused in an older owned test checkout without changing the reviewed lock.
for (const key of ['sourceFiles', 'files']) {
  if (JSON.stringify(kept[key]) !== JSON.stringify(manifest[key])) throw new Error(`Native proxy probe ${key} differ; review and update the source manifest`);
}
fs.mkdirSync(output, { recursive: true });
fs.writeFileSync(path.join(output, 'upstream_proxy_probe.go'), generated, 'utf8');
console.log(`Prepared original proxy trace and test at ${revision}`);
