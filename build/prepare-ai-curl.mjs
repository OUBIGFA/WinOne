// Reuse the selected Magpie parser, including its Windows shell quoting rules.
// Keep the whole paste module and its base-URL helper. No DOM editor is run.
import {createRequire} from 'node:module';
import {readFile,writeFile} from 'node:fs/promises';
import {resolve,join} from 'node:path';
import {execFileSync} from 'node:child_process';
const root=resolve(import.meta.dirname,'..'),source=resolve(process.argv[2]||'');
if(!process.argv[2])throw Error('Usage: prepare-ai-curl.mjs <Magpie-source>');
const require=createRequire(join(root,'apps/desktop/frontend/package.json'));
const {parse}=require('@babel/parser');
const code=await readFile(join(source,'internal/gui/assets/app.js'),'utf8');
const names=['withScheme','respellURL'],functions=names.map(name=>{
 const matches=parse(code,{sourceType:'script'}).program.body.filter(node=>node.type==='FunctionDeclaration'&&node.id.name===name);
 if(matches.length!==1)throw Error('Upstream curl parser changed: '+name);
 const node=matches[0];return code.slice(node.start,node.end);
});
const revision=execFileSync('git',['-C',source,'rev-parse','HEAD'],{encoding:'utf8',windowsHide:true}).trim();
// The current upstream owns all paste parsers in this lazy-loaded module,
// including environment/JSON/plain setup text and pasteClean. Keep it whole.
const pasted=await readFile(join(source,'internal/gui/assets/pasteread.js'),'utf8');
if(!pasted.includes('window.curlOf = function curlOf')||!pasted.includes('window.envOf = function envOf'))throw Error('Upstream paste module changed');
const destination=process.argv[3]?resolve(process.argv[3]):join(root,'apps/desktop/frontend/src/features/magpie-curl.js');
await writeFile(destination,['// Magpie '+revision+' / MIT. Generated by build/prepare-ai-curl.mjs.','const window = globalThis;',...functions,pasted,'const curlOf = window.curlOf, envOf = window.envOf;','export {curlOf, envOf};',''].join('\n'));
console.log('Prepared the upstream curl import parser at '+revision);
