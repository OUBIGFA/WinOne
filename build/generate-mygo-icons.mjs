// Generates the Lucide icons the MyGo desktop window uses.
//
// It scans apps/desktop-mygo for `icons.Name` references, takes each icon's
// node list from the locked lucide-react package (ISC, version in
// apps/desktop/frontend/package-lock.json) and writes plain SVG files plus
// the Go declarations that embed them. Names that are not Lucide icons must
// be declared by hand in kit/icons/custom.go.
//
//   node build/generate-mygo-icons.mjs          # write the files
//   node build/generate-mygo-icons.mjs --check  # fail when they are stale
import {readFileSync, writeFileSync, readdirSync, mkdirSync, rmSync, existsSync} from 'node:fs';
import {join, relative, resolve, dirname} from 'node:path';
import {fileURLToPath, pathToFileURL} from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const app = join(root, 'apps/desktop-mygo');
const iconDir = join(app, 'kit/icons');
const svgDir = join(iconDir, 'lucide');
const lucide = join(root, 'apps/desktop/frontend/node_modules/lucide-react');
const check = process.argv.includes('--check');

// Exported names map to icon modules, aliases included.
const exportsIndex = readFileSync(join(lucide, 'dist/esm/lucide-react.mjs'), 'utf8');
const modules = new Map();
for (const match of exportsIndex.matchAll(/export \{([^}]*)\} from '\.\/icons\/([a-z0-9-]+)\.mjs';/g)) {
  for (const part of match[1].split(',')) {
    const name = part.trim().replace(/^default as /, '');
    if (name) modules.set(name, match[2]);
  }
}

function goFiles(directory) {
  const files = [];
  for (const entry of readdirSync(directory, {withFileTypes: true})) {
    const path = join(directory, entry.name);
    if (entry.isDirectory()) files.push(...goFiles(path));
    else if (entry.name.endsWith('.go')) files.push(path);
  }
  return files;
}

const custom = new Set();
const customSource = join(iconDir, 'custom.go');
if (existsSync(customSource)) {
  for (const match of readFileSync(customSource, 'utf8').matchAll(/^\t([A-Z][A-Za-z0-9]*)\s*=/gm)) custom.add(match[1]);
}
const used = new Set();
for (const file of goFiles(app)) {
  if (file.startsWith(iconDir)) continue;
  for (const match of readFileSync(file, 'utf8').matchAll(/\bicons\.([A-Z][A-Za-z0-9]*)\b/g)) used.add(match[1]);
}
const names = [...used].filter(name => !custom.has(name) && name !== 'Icon').sort();
const missing = names.filter(name => !modules.has(name));
if (missing.length) {
  console.error('Not Lucide icons (declare them in kit/icons/custom.go): ' + missing.join(', '));
  process.exit(1);
}

const attribute = (name, value) => `${name.replace(/[A-Z]/g, c => '-' + c.toLowerCase())}="${String(value).replace(/&/g, '&amp;').replace(/"/g, '&quot;')}"`;
const files = new Map();
const declarations = [];
for (const name of names) {
  const file = modules.get(name);
  const {__iconNode} = await import(pathToFileURL(join(lucide, 'dist/esm/icons', file + '.mjs')).href);
  const children = __iconNode.map(([tag, attrs]) => `<${tag} ${Object.entries(attrs).filter(([key]) => key !== 'key').map(([key, value]) => attribute(key, value)).join(' ')}/>`).join('');
  files.set(file + '.svg', `<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${children}</svg>\n`);
  declarations.push([name, file]);
}
// Aligned as gofmt aligns a var block, so the file is already formatted.
const width = Math.max(0, ...declarations.map(([name]) => name.length));
const source = `// Code generated by build/generate-mygo-icons.mjs; DO NOT EDIT.

package icons

var (
${declarations.map(([name, file]) => `\t${name.padEnd(width)} = lucide("${file}")`).join('\n')}
)
`;

const goPath = join(iconDir, 'lucide_gen.go');
if (check) {
  const stale = [];
  if (!existsSync(goPath) || readFileSync(goPath, 'utf8') !== source) stale.push(relative(root, goPath));
  const present = existsSync(svgDir) ? readdirSync(svgDir) : [];
  for (const [file, svg] of files) {
    const path = join(svgDir, file);
    if (!existsSync(path) || readFileSync(path, 'utf8') !== svg) stale.push(relative(root, path));
  }
  for (const file of present) if (!files.has(file)) stale.push(relative(root, join(svgDir, file)) + ' (unused)');
  if (stale.length) {
    console.error('Icons are stale; run node build/generate-mygo-icons.mjs:\n' + stale.join('\n'));
    process.exit(1);
  }
  console.log(`icons current: ${files.size}`);
} else {
  rmSync(svgDir, {recursive: true, force: true});
  mkdirSync(svgDir, {recursive: true});
  for (const [file, svg] of files) writeFileSync(join(svgDir, file), svg);
  writeFileSync(goPath, source);
  console.log(`icons written: ${files.size}`);
}
