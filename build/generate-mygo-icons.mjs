// Generates the Solar Linear icons the MyGo desktop window uses.
//
// It scans apps/desktop-mygo for `icons.Name` references, looks each name up
// in third_party/solar-icons.json (surfaces.desktop) and writes the Solar
// SVG, colored by currentColor, plus the Go declarations that embed them.
// A new icon needs a mapping entry first; entries no code uses are rejected
// so the table stays the real inventory.
//
//   node build/generate-mygo-icons.mjs          # write the files
//   node build/generate-mygo-icons.mjs --check  # fail when they are stale
import {readFileSync, writeFileSync, readdirSync, mkdirSync, rmSync, existsSync} from 'node:fs';
import {join, relative} from 'node:path';
import {root, catalog, solarSVG, licenseText} from './solar-icons.mjs';

const app = join(root, 'apps/desktop-mygo');
const iconDir = join(app, 'kit/icons');
const svgDir = join(iconDir, 'solar');
const check = process.argv.includes('--check');
const mapping = catalog.surfaces.desktop.icons;

function goFiles(directory) {
  const files = [];
  for (const entry of readdirSync(directory, {withFileTypes: true})) {
    const path = join(directory, entry.name);
    if (entry.isDirectory()) files.push(...goFiles(path));
    else if (entry.name.endsWith('.go')) files.push(path);
  }
  return files;
}

const used = new Set();
for (const file of goFiles(app)) {
  if (file.startsWith(iconDir)) continue;
  for (const match of readFileSync(file, 'utf8').matchAll(/\bicons\.([A-Z][A-Za-z0-9]*)\b/g)) used.add(match[1]);
}
const names = [...used].filter(name => name !== 'Icon').sort();
const missing = names.filter(name => !mapping[name]);
if (missing.length) {
  console.error('No Solar icon mapped (add them to third_party/solar-icons.json surfaces.desktop): ' + missing.join(', '));
  process.exit(1);
}
const unused = Object.keys(mapping).filter(name => !used.has(name));
if (unused.length) {
  console.error('Mapped but unused desktop icons (remove them from third_party/solar-icons.json): ' + unused.join(', '));
  process.exit(1);
}

const files = new Map([['LICENSE.txt', licenseText()]]);
const declarations = [];
for (const name of names) {
  const file = mapping[name];
  files.set(file + '.svg', solarSVG(file) + '\n');
  declarations.push([name, file]);
}
// Aligned as gofmt aligns a var block, so the file is already formatted.
const width = Math.max(0, ...declarations.map(([name]) => name.length));
const source = `// Code generated by build/generate-mygo-icons.mjs; DO NOT EDIT.

package icons

var (
${declarations.map(([name, file]) => `\t${name.padEnd(width)} = solar("${file}")`).join('\n')}
)
`;

const goPath = join(iconDir, 'solar_gen.go');
const retired = [join(iconDir, 'lucide_gen.go'), join(iconDir, 'lucide'), join(iconDir, 'custom.go'), join(iconDir, 'custom')];
if (check) {
  const stale = [];
  if (!existsSync(goPath) || readFileSync(goPath, 'utf8') !== source) stale.push(relative(root, goPath));
  const present = existsSync(svgDir) ? readdirSync(svgDir) : [];
  for (const [file, svg] of files) {
    const path = join(svgDir, file);
    if (!existsSync(path) || readFileSync(path, 'utf8') !== svg) stale.push(relative(root, path));
  }
  for (const file of present) if (!files.has(file)) stale.push(relative(root, join(svgDir, file)) + ' (unused)');
  for (const path of retired) if (existsSync(path)) stale.push(relative(root, path) + ' (retired)');
  if (stale.length) {
    console.error('Icons are stale; run node build/generate-mygo-icons.mjs:\n' + stale.join('\n'));
    process.exit(1);
  }
  console.log(`icons current: ${declarations.length} names, ${files.size - 1} Solar files`);
} else {
  for (const path of retired) rmSync(path, {recursive: true, force: true});
  rmSync(svgDir, {recursive: true, force: true});
  mkdirSync(svgDir, {recursive: true});
  for (const [file, svg] of files) writeFileSync(join(svgDir, file), svg);
  writeFileSync(goPath, source);
  console.log(`icons written: ${declarations.length} names, ${files.size - 1} Solar files`);
}
